def main() -> None:
    root = Path(__file__).resolve().parents[2] / "data" / "nouns"
    total = 0
    added = 0
    missing: list[str] = []

    for json_path in sorted(root.glob("*.json")):
        file_flavors = FLAVORS.get(json_path.name)
        if file_flavors is None:
            print(f"[skip] no flavor table for {json_path.name}")
            continue
        data = json.loads(json_path.read_text(encoding="utf-8"))
        if not isinstance(data, list):
            raise SystemExit(f"unexpected structure in {json_path}")
        for entry in data:
            total += 1
            name = entry.get("name")
            if name in file_flavors:
                flavor = file_flavors[name]
                if not flavor.endswith("。"):
                    raise SystemExit(f"flavor for {name} must end with 。")
                length = len(flavor)
                if length < 30 or length > 90:
                    print(f"[warn] {name}: length={length} (40-80 推奨)")
                if "flavor" not in entry:
                    added += 1
                entry["flavor"] = flavor
            else:
                missing.append(f"{json_path.name}:{name}")
        json_path.write_text(
            json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
        )
        print(f"[ok] {json_path.name}: wrote {len(data)} entries")

    if missing:
        raise SystemExit("missing flavors:\n" + "\n".join(missing))

    print(f"\nDone. total entries scanned: {total}, newly added flavors: {added}")


